export const ROOM_STOCK_BY_ID = (room: RoomId) =>
  STOCK.filter((item) => item.room === room && !item.archive);

export const ARCHIVE_STOCK = STOCK.filter((item) => item.archive);

export function byRecentlyTraded(a: StockItem, b: StockItem) {
  return b.traded.localeCompare(a.traded);
}

export function formatPrice(value: number) {
  return new Intl.NumberFormat("en-IE", {
    style: "currency",
    currency: "EUR",
    minimumFractionDigits: value % 1 === 0 ? 0 : 2,
  }).format(value);
}

export function formatTraded(iso: string) {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-IE", {
    day: "numeric",
    month: "long",
  });
}

export function searchStock(query: string): StockItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\s+/).slice(0, 6);
  return STOCK.filter((item) => {
    const haystack = [
      item.title,
      item.maker,
      item.shelf,
      item.condition,
      item.year ? String(item.year) : "",
      item.note,
      ...item.tags,
    ]
      .join(" ")
      .toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}